create or replace view public.academy_overdue_installments with (security_invoker=true) as
select i.id, i.enrollment_id, i.installment_no, i.amount, i.paid_amount,
       (i.amount-i.paid_amount)::bigint as remaining_amount, i.due_date, i.status,
       s.id as student_id, s.student_no, s.full_name, s.mobile,
       c.id as course_id, c.title as course_title
from public.academy_installments i
join public.academy_enrollments e on e.id=i.enrollment_id
join public.academy_students s on s.id=e.student_id
join public.academy_courses c on c.id=e.course_id
where i.status in ('open','partial') and i.due_date < current_date;

create or replace view public.academy_course_finance with (security_invoker=true) as
select c.id as course_id, c.title as course_title,
       count(e.id)::int as enrollment_count,
       coalesce(sum(e.final_fee),0)::bigint as billed_total,
       coalesce(sum(f.paid_total),0)::bigint as paid_total,
       coalesce(sum(f.balance),0)::bigint as balance_total,
       case when coalesce(sum(e.final_fee),0)=0 then 0
            else round((coalesce(sum(f.paid_total),0)::numeric / sum(e.final_fee)::numeric)*100,1) end as collection_rate
from public.academy_courses c
left join public.academy_enrollments e on e.course_id=c.id and e.status in ('active','completed')
left join public.academy_enrollment_finance f on f.enrollment_id=e.id
group by c.id,c.title;

create or replace view public.academy_dashboard_summary with (security_invoker=true) as
select
  (select count(*)::int from public.academy_students where status='active') as active_students,
  (select count(*)::int from public.academy_courses where status='active') as active_courses,
  (select coalesce(sum(amount),0)::bigint from public.academy_payments) as collected_total,
  (select coalesce(sum(balance),0)::bigint from public.academy_enrollment_finance where balance>0) as receivables_total,
  (select count(*)::int from public.academy_overdue_installments) as overdue_installments,
  (select count(*)::int from public.academy_followups where status='open' and due_at <= now()+interval '24 hours') as due_followups,
  (select coalesce(sum(amount),0)::bigint from public.academy_payments where paid_at >= date_trunc('month',now())) as collected_this_month,
  (select coalesce(sum(amount),0)::bigint from public.academy_expenses where expense_date >= date_trunc('month',now())::date) as expenses_this_month,
  (select coalesce(sum(amount),0)::bigint from public.academy_teacher_payouts where paid_at >= date_trunc('month',now())) as teacher_payouts_this_month;

grant select on public.academy_overdue_installments, public.academy_course_finance, public.academy_dashboard_summary to authenticated;
