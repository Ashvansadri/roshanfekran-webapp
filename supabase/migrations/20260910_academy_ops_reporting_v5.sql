-- Academy Control Center v5 operational + reporting migration
create table if not exists public.academy_followups (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.academy_students(id) on delete cascade,
  due_at timestamptz not null,
  type text not null check (type in ('call','message','documents','payment','class','certificate','other')),
  status text not null default 'open' check (status in ('open','done','cancelled')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  assigned_to uuid references auth.users(id) on delete set null,
  note text,
  completed_at timestamptz,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.academy_expenses (
  id uuid primary key default gen_random_uuid(),
  expense_no bigint generated by default as identity unique,
  category text not null,
  title text not null,
  amount bigint not null check (amount > 0),
  expense_date date not null default current_date,
  method text not null default 'other' check (method in ('cash','card_transfer','bank_transfer','pos','other')),
  reference_no text,
  note text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.academy_teacher_payouts (
  id uuid primary key default gen_random_uuid(),
  payout_no bigint generated by default as identity unique,
  teacher_name text not null,
  course_id uuid references public.academy_courses(id) on delete set null,
  amount bigint not null check (amount > 0),
  period_label text,
  paid_at timestamptz not null default now(),
  method text not null default 'bank_transfer' check (method in ('cash','card_transfer','bank_transfer','other')),
  reference_no text,
  note text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

