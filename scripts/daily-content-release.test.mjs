import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const source=readFileSync(new URL("../supabase/functions/academy-gateway/index.ts",import.meta.url),"utf8");
const fn=source.match(/function dailyIsAvailable\([^\n]+/);
assert(fn,"Server-side daily publication guard must exist");
const dailyIsAvailable=vm.runInNewContext(fn[0].replaceAll(":any","").replaceAll(":string","")+";dailyIsAvailable");
const today="2026-10-25";
for(const status of ["draft","archived",null])assert.equal(dailyIsAvailable({status,publish_date:today},today),false);
for(const publish_date of ["2026-10-26","2026-11-01","invalid",""])assert.equal(dailyIsAvailable({status:"published",publish_date},today),false);
for(const publish_date of ["2026-10-24","2026-10-25"])assert.equal(dailyIsAvailable({status:"published",publish_date},today),true);
const mark=source.slice(source.indexOf("if(b.action==='daily_mark')"),source.indexOf("if(b.action==='push_config')"));
assert(mark.includes("tehranToday()"),"Daily completion must use academy-local date");
assert(mark.includes("publish_date=lte."),"Database query must filter future content");
assert(mark.includes("dailyIsAvailable(rows[0],today)"),"Fail-closed application-level guard required");
assert(mark.includes("gatewayHttpError(403"),"Unavailable daily content must return forbidden");
assert(mark.includes("student_id=eq.")&&mark.includes("course_id=eq."),"Course access must be student-scoped");
const push=source.slice(source.indexOf("if(b.action==='daily_admin_push_batch')"),source.indexOf("if(b.action==='daily_admin_push_cleanup')"));
assert(push.includes("publish_date=lte."),"Manual push must not expose future content");
assert.equal((push.match(/push_sent_at=is.null/g)||[]).length,2,"Manual push must reject previously sent content");
console.log("PASS: future/draft daily completions blocked and manual push restricted to released unsent content");
